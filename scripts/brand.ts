/**
 * The story film, built from brand/film/ and rendered frame by frame in a browser at 1920x1080 and 60 fps, with
 * its score (synthesised by the film itself), into .film/openbelt-story-1080.mp4 and -720.mp4. `--page` stops
 * at .film/story.html, the film with its player, to watch it.
 */
const film = (args: ReadonlyArray<string>) => {
  mkdirSync(FILM.out, { recursive: true })

  const page = join(FILM.out, "story.html")

  writeFileSync(page, filmHtml())
  console.log(`brand: ${relative(ROOT, page)}`)

  if (args.includes("--page")) return

  if (Bun.which("ffmpeg") === null)
    throw new Error("brand film needs ffmpeg to encode the video: brew install ffmpeg")

  const frames = join(FILM.out, "frames")
  const wav = join(FILM.out, "score.wav")

  rmSync(frames, { recursive: true, force: true })
  mkdirSync(frames, { recursive: true })

  try {
    ab("set", "viewport", String(FILM.width), String(FILM.height))
    ab("open", `file://${page}`)
    ab("eval", "document.fonts.ready.then(() => true)")

    const length = FilmLength(ab("eval", "FILM.duration"))
    const count = Math.ceil(length * FILM.fps)

    for (let i = 0; i < count; i += FILM.batch) {
      const urls = FilmFrames(
        ab(
          "eval",
          `(() => { const c = document.getElementById("film"), out = []
          if (c.width !== ${FILM.width} || c.height !== ${FILM.height}) throw new Error("the canvas is " + c.width + "x" + c.height)
          for (let k = ${i}; k < ${Math.min(count, i + FILM.batch)}; k++) { __seek(k / ${FILM.fps}); out.push(c.toDataURL("image/jpeg", 1)) }
          return out })()`,
        ),
      )

      for (const [k, url] of urls.entries())
        writeFileSync(
          join(frames, `${String(i + k).padStart(5, "0")}.jpg`),
          Buffer.from(url.split(",")[1] ?? "", "base64"),
        )

      if (i % 600 === 0) console.log(`brand: film frame ${i} of ${count}`)
    }

    writeFileSync(wav, Buffer.from(FilmWav(ab("eval", "__wav(44100)")), "base64"))
  } finally {
    ab("close")
  }

  for (const [height, crf, audio] of [
    [1080, "14", "192k"],
    [720, "16", "160k"],
  ] as const) {
    const out = join(FILM.out, `openbelt-story-${height}.mp4`)

    const r = Bun.spawnSync(
      [
        "ffmpeg",
        "-loglevel",
        "error",
        "-y",
        "-framerate",
        String(FILM.fps),
        "-i",
        join(frames, "%05d.jpg"),
        "-i",
        wav,
        "-vf",
        `scale=-2:${height}:flags=lanczos`,
        "-c:v",
        "libx264",
        "-preset",
        "slow",
        "-tune",
        "animation",
        "-profile:v",
        "high",
        "-pix_fmt",
        "yuv420p",
        "-crf",
        crf,
        "-c:a",
        "aac",
        "-b:a",
        audio,
        "-shortest",
        "-movflags",
        "+faststart",
        out,
      ],
      { stdout: "inherit", stderr: "inherit" },
    )

    if (r.exitCode !== 0) throw new Error(`brand film: ffmpeg failed to encode ${out}`)

    console.log(`brand: ${relative(ROOT, out)} (${Math.round(statSync(out).size / 1048576)} MB)`)
  }

  rmSync(frames, { recursive: true, force: true })
  console.log(
    "brand: upload both to R2 under a new story/<date> folder, then point www/index.html at it (brand/AGENTS.md, The story film)",
  )
}

