const literalEnd = (text: string, at: number): number => {
  const quote = text[at]
  let i = at + 1

  while (i < text.length && text[i] !== quote) {
    if (text[i] === "\\") i += 2
    else if (quote === "`" && text.startsWith("${", i)) i = codeEnd(text, i + 2, "}")
    else i += 1
  }

  return i + 1
}

const codeEnd = (text: string, at: number, close: string): number => {
  let depth = 0
  let i = at

  while (i < text.length) {
    const c = text[i] ?? ""

    if (c === '"' || c === "'" || c === "`") i = literalEnd(text, i)
    else if (depth === 0 && c === close) return i + 1
    else {
      if ("([{".includes(c)) depth += 1

      if (")]}".includes(c)) depth -= 1
      i += 1
    }
  }

  return i
}

type Literal = {
  readonly raw: string
  readonly fixed: string
  readonly live: boolean
}

const literalsIn = (code: string): ReadonlyArray<Literal> => {
  const found: Array<Literal> = []
  let i = 0

  while (i < code.length) {
    const c = code[i] ?? ""

    if (c !== '"' && c !== "'" && c !== "`") {
      i += 1
      continue
    }

    const end = literalEnd(code, i)
    const raw = code.slice(i, end)
    let fixed = ""
    let live = false
    let j = 1

    while (j < raw.length - 1) {
      if (c === "`" && raw.startsWith("${", j)) {
        const close = codeEnd(raw, j + 2, "}")
        const inner = raw.slice(j + 2, close - 1)
        const nested = literalsIn(inner)
        let bare = inner

        for (const l of nested) bare = bare.split(l.raw).join("")

        if (/[A-Za-z_$]/.test(bare) || nested.some((l) => l.live)) live = true

        found.push(...nested)
        fixed += " "
        j = close
      } else {
        fixed += raw[j] ?? ""
        j += 1
      }
    }

    found.push({ raw, fixed: fixed.split(/<[^>]*>/).join(" "), live })
    i = end
  }

  return found
}

