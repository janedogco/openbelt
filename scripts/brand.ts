/** Samples per pixel along each side, for the antialiased edges. */
const SAMPLES = 8

const rgb = (hex: string) => [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16))

const inTile = (u: number, v: number, r: number) => {
  const dx = Math.max(r - u, 0, u - (1 - r))
  const dy = Math.max(r - v, 0, v - (1 - r))

  return dx * dx + dy * dy <= r * r
}

/** The slot (logo/slot.svg, M0 0H3V3H0V2H2V1H0Z) at `size` of the tile, centred: a square less its notch. */
const inSlot = (u: number, v: number, size: number) => {
  const x = ((u - (1 - size) / 2) / size) * 3
  const y = ((v - (1 - size) / 2) / size) * 3

  return x >= 0 && x < 3 && y >= 0 && y < 3 && !(x < 2 && y >= 1 && y < 2)
}

/** The share of the way down where the app icon's tile reaches its bottom colour (DESIGN.md, the app icons). */
const TILE_FADE = 0.7

const mix = (a: ReadonlyArray<number>, b: ReadonlyArray<number>, t: number) =>
  a.map((c, i) => c + ((b[i] ?? 0) - c) * Math.min(Math.max(t, 0), 1))

/**
 * An icon's scanlines as a PNG stores them before compression: each row a 0 (no filter), then RGBA.
 * A favicon is flat: a dark tile, a light mark. An app icon is Ink: logo.appIcon's gradients, top to bottom.
 */
const iconScanlines = (side: number, kind: "app" | "favicon", r: number) => {
  const d = design()
  const slot = iconRatio(kind)
  const flat = (hex: string) => [rgb(hex), rgb(hex)] as const

  const [tileTop, tileBottom] =
    kind === "favicon" ? flat(d.colors["neutral-dark"] ?? "#000000") : d.logo.appIcon.tile.map(rgb)

  const [markTop, markBottom] =
    kind === "favicon" ? flat(d.colors["primary-light"] ?? "#ffffff") : d.logo.appIcon.mark.map(rgb)

  const raw = Buffer.alloc((side * 4 + 1) * side)

  for (let y = 0; y < side; y++) {
    for (let x = 0; x < side; x++) {
      let tile = 0
      const sum = [0, 0, 0]

      for (let sy = 0; sy < SAMPLES; sy++) {
        for (let sx = 0; sx < SAMPLES; sx++) {
          const u = (x + (sx + 0.5) / SAMPLES) / side
          const v = (y + (sy + 0.5) / SAMPLES) / side

          if (inTile(u, v, r)) {
            tile += 1

            const colour = inSlot(u, v, slot)
              ? mix(markTop ?? [], markBottom ?? [], (v - (1 - slot) / 2) / slot)
              : mix(tileTop ?? [], tileBottom ?? [], v / TILE_FADE)

            for (let c = 0; c < 3; c++) sum[c] = (sum[c] ?? 0) + (colour[c] ?? 0)
          }
        }
      }

      const at = y * (side * 4 + 1) + 1 + x * 4

      if (tile > 0) for (let c = 0; c < 3; c++) raw[at + c] = Math.round((sum[c] ?? 0) / tile)

      raw[at + 3] = Math.round((tile / (SAMPLES * SAMPLES)) * 255)
    }
  }

  return raw
}

const PNG_SIGNATURE = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])

const pngChunk = (type: string, data: Buffer) => {
  const body = Buffer.concat([Buffer.from(type, "latin1"), data])
  const head = Buffer.alloc(4)
  const tail = Buffer.alloc(4)

  head.writeUInt32BE(data.length)
  tail.writeUInt32BE(crc32(body))

  return Buffer.concat([head, body, tail])
}

const png = (side: number, scanlines: Buffer) => {
  const header = Buffer.alloc(13)

  header.writeUInt32BE(side, 0)
  header.writeUInt32BE(side, 4)
  header[8] = 8
  header[9] = 6

  return Buffer.concat([
    PNG_SIGNATURE,
    pngChunk("IHDR", header),
    pngChunk("IDAT", deflateSync(scanlines, { level: 9 })),
    pngChunk("IEND", Buffer.alloc(0)),
  ])
}

/** A PNG's scanlines, uncompressed: compared rather than its bytes, which differ between zlib builds. */
const scanlinesOf = (file: Buffer) => {
  const data: Array<Buffer> = []

  for (let at = 8; at + 8 <= file.length;) {
    const length = file.readUInt32BE(at)

    if (file.toString("latin1", at + 4, at + 8) === "IDAT")
      data.push(file.subarray(at + 8, at + 8 + length))
    at += 12 + length
  }

  return inflateSync(Buffer.concat(data))
}

