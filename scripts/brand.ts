const isRail = (property: string, value: string) => {
  const v = value.trim()

  if (/^(0|none|initial|inherit|unset)\b/.test(v)) return false

  const colour =
    /var\(--openbelt-color-([a-z-]+)\)|#[0-9a-f]{3,8}\b|\b(rgba?|hsla?|oklch)\(|currentColor/i.exec(
      v,
    )

  const coloured =
    colour !== null &&
    !(colour[1] !== undefined && ["border", "border-strong"].includes(colour[1])) &&
    !/^transparent$/.test(v)

  if (property.endsWith("-color")) return coloured

  const width = /(\d+(?:\.\d+)?)px/.exec(v)

  return coloured || (width?.[1] !== undefined && Number(width[1]) > 1)
}

