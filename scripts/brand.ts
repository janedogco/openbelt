const copyOf = (rel: string) => {
  const source =
    rel === "css/openbelt.css"
      ? Buffer.from(
          readFileSync(join(BRAND, rel), "utf8")
            .replace(/^@import "([^"]+)";$/gm, (_line, imported: string) => {
              const path = join(dirname(rel), imported)

              return readFileSync(join(BRAND, path), "utf8").replace(
                /url\("([^"]+)"\)/g,
                (_url, asset: string) =>
                  `url("${relative(dirname(rel), join(dirname(path), asset))}")`,
              )
            })
            .trimEnd() + "\n",
        )
      : readFileSync(join(BRAND, rel))

  if (rel.endsWith(".css")) {
    return Buffer.concat([
      Buffer.from(`/* generated by bun run brand sync from brand/${rel}: ${GENERATED} */\n`),
      source,
    ])
  }

  if (rel.endsWith(".svg")) {
    return Buffer.concat([
      source,
      Buffer.from(`<!-- generated by bun run brand sync from brand/${rel}: ${GENERATED} -->\n`),
    ])
  }

  return source
}

