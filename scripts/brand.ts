const CARD = { width: 1200, height: 630, fps: 60 }

/** What og-card.html's start() answers: how long its loop is and when the name is whole, in seconds. */
const CardFilm = Schema.decodeUnknownSync(
  Schema.Struct({ loop: Schema.Number.check(Schema.isGreaterThan(0)), still: Schema.Number }),
)

const svgUri = (text: string) => `data:image/svg+xml;base64,${Buffer.from(text).toString("base64")}`

/**
 * The link preview card (og-card.html), rendered frame by frame: logo/social/og.mp4, a loop iMessage plays in the
 * preview (og:video), and og.png, the moment the name is whole, for everything that shows a still (og:image).
 */
const card = async () => {
  if (Bun.which("ffmpeg") === null)
    throw new Error("brand card needs ffmpeg to encode the video: brew install ffmpeg")

  const d = design()
  const paper = d.colors["primary-dark"] ?? "white"

  const film = {
    colors: {
      backdrop: d.colors["backdrop-dark"] ?? "black",
      paper,
      ink: d.colors["neutral-dark"] ?? "black",
    },
    tileRadius: tileRadius(),
    tile: svgUri(read("logo/tile-light.svg")),
    geometry: LOGO,
    wordmark: svgUri(read("logo/openbelt-white.svg").replace("#fffefb", paper)),
    icons: CARD_ICONS.map((name) => {
      const body = icons().icons.find((i) => i.name === name)?.body

      if (body === undefined)
        throw new Error(`brand card: no icon "${name}": bun run brand icon add ${name}`)

      return body
    }),
    hues: CARD_HUES,
  }

  const html = readFileSync(join(import.meta.dir, "og-card.html"), "utf8")

  const matter = readFileSync(
    Bun.fileURLToPath(import.meta.resolve("matter-js/build/matter.min.js")),
    "utf8",
  )

  const video = join(BRAND, "logo/social/og.mp4")
  const view = new Bun.WebView({ width: CARD.width, height: CARD.height })

  try {
    await view.navigate(`data:text/html;base64,${Buffer.from(html).toString("base64")}`)
    await Bun.sleep(300)

    // evaluate() takes one expression, and matter.js is a script: run it through a global eval.
    await view.evaluate(`((0, eval)(${JSON.stringify(matter)}), true)`)

    const { loop, still } = CardFilm(await view.evaluate(`start(${JSON.stringify(film)})`))
    const frames = Math.round(loop * CARD.fps)
    const stillFrame = Math.round(still * CARD.fps)

    // The view's screenshots are 2x; ffmpeg scales each to the card's size as it encodes.
    const ffmpeg = Bun.spawn(
      [
        "ffmpeg",
        "-v",
        "error",
        "-y",
        "-f",
        "image2pipe",
        "-framerate",
        String(CARD.fps),
        "-c:v",
        "png",
        "-i",
        "-",
        "-vf",
        `scale=${CARD.width}:${CARD.height}:flags=lanczos`,
        "-c:v",
        "libx264",
        "-preset",
        "slow",
        "-crf",
        "20",
        "-pix_fmt",
        "yuv420p",
        "-movflags",
        "+faststart",
        "-an",
        video,
      ],
      { stdin: "pipe", stdout: "inherit", stderr: "inherit" },
    )

    for (let frame = 0; frame < frames; frame++) {
      await view.evaluate(`seek(${frame / CARD.fps})`)

      const shot = new Uint8Array(await view.screenshot({ format: "png", encoding: "buffer" }))

      await ffmpeg.stdin.write(shot)
      await ffmpeg.stdin.flush()

      if (frame === stillFrame) {
        const frameStill = await new Bun.Image(shot).resize(CARD.width, CARD.height).png().bytes()

        write(join(BRAND, "logo/social/og.png"), new Uint8Array(frameStill))
      }
    }

    await ffmpeg.stdin.end()

    if ((await ffmpeg.exited) !== 0) throw new Error("brand card: ffmpeg failed to encode og.mp4")
  } finally {
    view.close()
  }

  console.log(`brand: logo/social/og.mp4 (${Math.round(statSync(video).size / 1024)} KB), og.png`)
  sync()
}

/** The story film the homepage plays (www/index.html): its source is brand/film/, its renders live in R2. */
const FILM = { width: 1920, height: 1080, fps: 60, batch: 20, out: join(ROOT, ".film") }

const AGENT_BROWSER = join(ROOT, "node_modules/.bin/agent-browser")

/** What the film page answers: its length in seconds. */
const FilmLength = Schema.decodeUnknownSync(
  Schema.fromJsonString(Schema.Number.check(Schema.isGreaterThan(0))),
)

const FilmFrames = Schema.decodeUnknownSync(Schema.fromJsonString(Schema.Array(Schema.String)))

const FilmWav = Schema.decodeUnknownSync(Schema.fromJsonString(Schema.String))

/** brand/film/ as one standalone page: the fonts, three.js, the kit, the story and the player inlined. */
const face = (family: string, path: string) =>
  `@font-face{font-family:"${family}";src:url(data:font/woff2;base64,${readFileSync(path).toString("base64")}) format("woff2");font-weight:100 900;font-display:block}`

