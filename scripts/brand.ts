const ab = (...a: ReadonlyArray<string>) => {
  const r = Bun.spawnSync([AGENT_BROWSER, "--session", "brand-film", ...a], {
    stdout: "pipe",
    stderr: "pipe",
  })

  if (r.exitCode !== 0)
    throw new Error(`agent-browser ${a[0]}: ${r.stderr.toString().slice(0, 1000)}`)

  return r.stdout.toString().trim()
}

