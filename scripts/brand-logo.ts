import { readFileSync } from "node:fs"

const wordmark = readFileSync(new URL("../brand/logo/wordmark.svg", import.meta.url), "utf8")

const tile = 1000

const wordmarkScale = 3 / 4

const gap = tile / 4

const baseline = (-tile * (1 - wordmarkScale)) / 2

const descender = Number(Math.max(0, baseline + 211.3 * wordmarkScale).toFixed(6))

const wordmarkX = Number((tile + gap - 1303.3 * wordmarkScale).toFixed(6))

export const LOGO = {
  tile,
  wordmarkScale,
  gap,
  width: tile + gap + 5973.3 * wordmarkScale,
  height: tile + descender,
  descender,
} as const

const decimal = (n: number) => String(Number(n.toFixed(2)))

export const slotPath = (side: number, ratio: number, top = 0) => {
  const start = (side * (1 - ratio)) / 2
  const size = side * ratio
  const x = (n: number) => decimal(start + (size * n) / 3)
  const y = (n: number) => decimal(top + start + (size * n) / 3)

  return `M${x(0)} ${y(0)}H${x(3)}V${y(3)}H${x(0)}V${y(2)}H${x(2)}V${y(1)}H${x(0)}Z`
}

export const logoSvg = (radius: number, markRatio: number, color = "currentColor") => {
  const r = Number((radius * LOGO.tile).toFixed(2))
  const edge = LOGO.tile - r
  const arc = `A${r} ${r} 0 0 1`
  const tileOutline = `M${r} -1000H${edge}${arc} 1000 -${edge}V-${r}${arc} ${edge} 0H${r}${arc} 0 -${r}V-${edge}${arc} ${r} -1000Z${slotPath(LOGO.tile, markRatio, -LOGO.tile)}`
  const letters = wordmark.match(/<path\b[^>]*\/>/g)?.join("")

  if (!letters) throw new Error("brand/logo/wordmark.svg: supply the outlined wordmark paths")

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -1000 ${LOGO.width} ${LOGO.height}" role="img" aria-label="OpenBelt"><title>OpenBelt</title><path fill="${color}" fill-rule="evenodd" d="${tileOutline}"/><g transform="translate(${wordmarkX} ${baseline}) scale(${LOGO.wordmarkScale})">${letters.replaceAll('fill="currentColor"', `fill="${color}"`)}</g></svg>\n`
}

